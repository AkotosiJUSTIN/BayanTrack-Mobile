  static bool contains(double latitude, double longitude) {
    if (latitude < south ||
        latitude > north ||
        longitude < west ||
        longitude > east) {
      return false;
    }

    // Ray-casting point-in-polygon.
    bool inside = false;
    for (int i = 0, j = boundary.length - 1; i < boundary.length; j = i++) {
      final yi = boundary[i].$1;
      final xi = boundary[i].$2;
      final yj = boundary[j].$1;
      final xj = boundary[j].$2;

      final intersects =
          ((yi > latitude) != (yj > latitude)) &&
          (longitude <
              (xj - xi) * (latitude - yi) / ((yj - yi) + 0.0000000001) + xi);

      if (intersects) {
        inside = !inside;
      }
    }
    return inside;
  }
